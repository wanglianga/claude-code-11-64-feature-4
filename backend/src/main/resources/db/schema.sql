-- ============================================================================
-- 排水管道结构缺陷普查评估平台 · PostgreSQL 18 schema
-- 设计要点：
--   1. 资产（井/管段）全部挂版本，观察归属按“检查发生时有效版本”固定
--   2. 新旧管段通过 app_segment_mapping 保留里程映射，历史缺陷不静默搬移
--   3. 观察先产生对齐候选，再固定归属；聚类后区分重复/冲突
--   4. 评估数据集只引用确认后的聚类，冲突位置暂停排序
-- 所有表使用 IF NOT EXISTS，可重复执行。
-- ============================================================================

-- ---------------------------------------------------------------- 账户与令牌
CREATE TABLE IF NOT EXISTS app_user (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username        VARCHAR(64)  NOT NULL UNIQUE,
    password_hash   VARCHAR(255) NOT NULL,
    display_name    VARCHAR(64)  NOT NULL,
    role            VARCHAR(16)  NOT NULL DEFAULT 'ENGINEER',
    created_at      TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT chk_user_role CHECK (role IN ('ENGINEER','ADMIN'))
);

CREATE TABLE IF NOT EXISTS app_login_token (
    token       VARCHAR(128) PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES app_user(id),
    expires_at  TIMESTAMP NOT NULL,
    created_at  TIMESTAMP NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------- 资产版本域
CREATE TABLE IF NOT EXISTS app_asset_version (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_no    VARCHAR(32)  NOT NULL UNIQUE,
    name          VARCHAR(128) NOT NULL,
    effective_at  TIMESTAMP    NOT NULL,
    status        VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    note          TEXT,
    created_at    TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT chk_av_status CHECK (status IN ('DRAFT','ACTIVE','SUPERSEDED'))
);

CREATE TABLE IF NOT EXISTS app_manhole (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id    BIGINT NOT NULL REFERENCES app_asset_version(id),
    manhole_code  VARCHAR(32) NOT NULL,
    geom_x        NUMERIC(12,3),
    geom_y        NUMERIC(12,3),
    created_at    TIMESTAMP NOT NULL DEFAULT now(),
    UNIQUE (version_id, manhole_code)
);

-- 管段：同一物理管段在不同版本中有不同行，parent_segment_id 指向上一版本行
CREATE TABLE IF NOT EXISTS app_pipe_segment (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id           BIGINT NOT NULL REFERENCES app_asset_version(id),
    segment_code         VARCHAR(32) NOT NULL,
    upstream_mh_id       BIGINT REFERENCES app_manhole(id),
    downstream_mh_id     BIGINT REFERENCES app_manhole(id),
    length_m             NUMERIC(10,3) NOT NULL,
    flow_direction       VARCHAR(16) NOT NULL,
    material             VARCHAR(32),
    diameter_mm          INTEGER,
    parent_segment_id    BIGINT REFERENCES app_pipe_segment(id),
    lifecycle_status     VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    created_at           TIMESTAMP NOT NULL DEFAULT now(),
    UNIQUE (version_id, segment_code),
    CONSTRAINT chk_ps_flow CHECK (flow_direction IN ('UP_TO_DOWN','DOWN_TO_UP')),
    CONSTRAINT chk_ps_lc   CHECK (lifecycle_status IN ('ACTIVE','SPLIT','MERGED','RETIRED'))
);

-- 新旧管段里程映射：坐标均为“沿管段走向、上游井为 0”的归一里程
CREATE TABLE IF NOT EXISTS app_segment_mapping (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    old_segment_id   BIGINT NOT NULL REFERENCES app_pipe_segment(id),
    new_segment_id   BIGINT NOT NULL REFERENCES app_pipe_segment(id),
    old_start_m      NUMERIC(10,3) NOT NULL,
    old_end_m        NUMERIC(10,3) NOT NULL,
    new_start_m      NUMERIC(10,3) NOT NULL,
    new_end_m        NUMERIC(10,3) NOT NULL,
    basis            VARCHAR(32) NOT NULL,
    note             TEXT,
    created_at       TIMESTAMP NOT NULL DEFAULT now(),
    CONSTRAINT chk_sm_basis CHECK (basis IN ('STATION_EQUIVALENCE','SURVEY_MEASURE','AS_BUILT_CLIP'))
);

-- ---------------------------------------------------------------- 检测归档域
CREATE TABLE IF NOT EXISTS app_contractor_batch (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_code           VARCHAR(64) NOT NULL UNIQUE,
    contractor           VARCHAR(128) NOT NULL,
    inspected_at         TIMESTAMP NOT NULL,
    grading_standard     VARCHAR(32) NOT NULL,
    direction_convention VARCHAR(64) NOT NULL,
    content_hash         VARCHAR(128),
    created_at           TIMESTAMP NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS app_video (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id        BIGINT NOT NULL REFERENCES app_contractor_batch(id),
    video_code      VARCHAR(64) NOT NULL,
    file_uri        VARCHAR(255) NOT NULL,
    segment_hint    VARCHAR(32) NOT NULL,
    start_m         NUMERIC(10,3) NOT NULL,
    end_m           NUMERIC(10,3) NOT NULL,
    -- 视频里程方向：FORWARD 与管段归一里程同向；REVERSED 为反向里程（0 在下游井）
    station_direction VARCHAR(8) NOT NULL,
    content_hash    VARCHAR(128),
    duplicate_of_id BIGINT REFERENCES app_video(id),
    created_at      TIMESTAMP NOT NULL DEFAULT now(),
    UNIQUE (batch_id, video_code),
    CONSTRAINT chk_v_dir CHECK (station_direction IN ('FORWARD','REVERSED'))
);

CREATE TABLE IF NOT EXISTS app_observation (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    video_id          BIGINT NOT NULL REFERENCES app_video(id),
    batch_id          BIGINT NOT NULL REFERENCES app_contractor_batch(id),
    defect_type       VARCHAR(32) NOT NULL,
    raw_grade         VARCHAR(8) NOT NULL,
    station_start_m   NUMERIC(10,3) NOT NULL,
    station_end_m     NUMERIC(10,3) NOT NULL,
    evidence_uri      VARCHAR(255),
    evidence_strength VARCHAR(8) NOT NULL,
    status            VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    duplicate_of_id   BIGINT REFERENCES app_observation(id),
    cluster_id        BIGINT,
    created_at        TIMESTAMP NOT NULL DEFAULT now(),
    CONSTRAINT chk_o_type CHECK (defect_type IN ('CRACK','DEFORMATION','LEAK','JOINT_DISLOCATION')),
    CONSTRAINT chk_o_ev   CHECK (evidence_strength IN ('FULL','PARTIAL','SPARSE')),
    CONSTRAINT chk_o_st   CHECK (status IN ('PENDING','CONFIRMED','DUPLICATE','QUARANTINED'))
);

-- ---------------------------------------------------------------- 等级标准与判读规则
CREATE TABLE IF NOT EXISTS app_grade_standard (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    standard_code    VARCHAR(32) NOT NULL,
    raw_grade        VARCHAR(8)  NOT NULL,
    normalized_grade INTEGER     NOT NULL,
    UNIQUE (standard_code, raw_grade),
    CONSTRAINT chk_gs_g CHECK (normalized_grade BETWEEN 1 AND 4)
);

CREATE TABLE IF NOT EXISTS app_judgement_rule (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    defect_type       VARCHAR(32) NOT NULL UNIQUE,
    min_grade         INTEGER NOT NULL,
    min_length_m      NUMERIC(10,3) NOT NULL DEFAULT 0,
    required_evidence VARCHAR(8) NOT NULL,
    enabled           BOOLEAN NOT NULL DEFAULT true,
    updated_at        TIMESTAMP NOT NULL DEFAULT now(),
    CONSTRAINT chk_jr_type CHECK (defect_type IN ('CRACK','DEFORMATION','LEAK','JOINT_DISLOCATION')),
    CONSTRAINT chk_jr_ev   CHECK (required_evidence IN ('FULL','PARTIAL','SPARSE'))
);

-- ---------------------------------------------------------------- 位置对齐域
CREATE TABLE IF NOT EXISTS app_alignment_candidate (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    observation_id  BIGINT NOT NULL REFERENCES app_observation(id),
    segment_id      BIGINT NOT NULL REFERENCES app_pipe_segment(id),
    asset_version_id BIGINT NOT NULL REFERENCES app_asset_version(id),
    norm_start_m    NUMERIC(10,3) NOT NULL,
    norm_end_m      NUMERIC(10,3) NOT NULL,
    score           NUMERIC(6,3) NOT NULL,
    selected        BOOLEAN NOT NULL DEFAULT false,
    reason          TEXT NOT NULL,
    created_at      TIMESTAMP NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_ac_obs ON app_alignment_candidate(observation_id);

-- 固定归属：检查时点有效版本 + 归一里程，之后永不被测绘修订改写
CREATE TABLE IF NOT EXISTS app_observation_attribution (
    observation_id   BIGINT PRIMARY KEY REFERENCES app_observation(id),
    segment_id       BIGINT NOT NULL REFERENCES app_pipe_segment(id),
    asset_version_id BIGINT NOT NULL REFERENCES app_asset_version(id),
    norm_start_m     NUMERIC(10,3) NOT NULL,
    norm_end_m       NUMERIC(10,3) NOT NULL,
    fixed_at         TIMESTAMP NOT NULL DEFAULT now(),
    note             TEXT
);

-- ---------------------------------------------------------------- 缺陷聚类域
CREATE TABLE IF NOT EXISTS app_defect_cluster (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cluster_code      VARCHAR(48),
    segment_id        BIGINT NOT NULL REFERENCES app_pipe_segment(id),
    asset_version_id  BIGINT NOT NULL REFERENCES app_asset_version(id),
    defect_type       VARCHAR(32) NOT NULL,
    norm_start_m      NUMERIC(10,3) NOT NULL,
    norm_end_m        NUMERIC(10,3) NOT NULL,
    status            VARCHAR(16) NOT NULL,
    conflict_flag     BOOLEAN NOT NULL DEFAULT false,
    resolved_grade    INTEGER,
    resolution_note   TEXT,
    resolved_by       BIGINT REFERENCES app_user(id),
    resolved_at       TIMESTAMP,
    created_at        TIMESTAMP NOT NULL DEFAULT now(),
    CONSTRAINT chk_dc_status CHECK (status IN ('ACTIVE','CONFLICT','ADJUDICATED','BELOW_RULE'))
);

CREATE TABLE IF NOT EXISTS app_cluster_member (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cluster_id        BIGINT NOT NULL REFERENCES app_defect_cluster(id),
    observation_id    BIGINT NOT NULL UNIQUE REFERENCES app_observation(id),
    member_role       VARCHAR(16) NOT NULL,
    grade_at_inspection INTEGER NOT NULL,
    evidence_strength VARCHAR(8) NOT NULL,
    batch_id          BIGINT NOT NULL,
    CONSTRAINT chk_cm_role CHECK (member_role IN ('PRIMARY','DUPLICATE'))
);

-- ---------------------------------------------------------------- 评估数据集域
CREATE TABLE IF NOT EXISTS app_dataset (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_code      VARCHAR(64) NOT NULL UNIQUE,
    as_of_version_id  BIGINT NOT NULL REFERENCES app_asset_version(id),
    scoring_mode      VARCHAR(16) NOT NULL,
    status            VARCHAR(16) NOT NULL DEFAULT 'GENERATED',
    generated_at      TIMESTAMP NOT NULL DEFAULT now(),
    generated_by      BIGINT REFERENCES app_user(id),
    formula_note      TEXT,
    CONSTRAINT chk_ds_mode CHECK (scoring_mode IN ('MAX_SEVERITY','BURDEN'))
);

CREATE TABLE IF NOT EXISTS app_dataset_segment_score (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_id           BIGINT NOT NULL REFERENCES app_dataset(id),
    segment_id           BIGINT NOT NULL REFERENCES app_pipe_segment(id),
    max_grade            INTEGER,
    burden_score         NUMERIC(12,3),
    rank_no              INTEGER,
    ranking_paused       BOOLEAN NOT NULL DEFAULT false,
    pause_reasons        TEXT,
    eligible_cluster_count INTEGER NOT NULL DEFAULT 0,
    conflict_count       INTEGER NOT NULL DEFAULT 0,
    evidence_completeness NUMERIC(5,4),
    explanation          TEXT NOT NULL,
    UNIQUE (dataset_id, segment_id)
);

-- 图纸修订影响清单
CREATE TABLE IF NOT EXISTS app_dataset_impact (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_id       BIGINT NOT NULL REFERENCES app_dataset(id),
    old_segment_id   BIGINT NOT NULL REFERENCES app_pipe_segment(id),
    new_segment_id   BIGINT REFERENCES app_pipe_segment(id),
    impact_type      VARCHAR(16) NOT NULL,
    inherited_count  INTEGER NOT NULL DEFAULT 0,
    quarantined_count INTEGER NOT NULL DEFAULT 0,
    note             TEXT,
    CONSTRAINT chk_di_type CHECK (impact_type IN ('SPLIT','MERGE','RETAIN','RETIRE'))
);

-- 审计日志（裁决、去重等关键动作）
CREATE TABLE IF NOT EXISTS app_audit_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT REFERENCES app_user(id),
    action      VARCHAR(64) NOT NULL,
    target_ref  VARCHAR(128),
    detail      TEXT,
    created_at  TIMESTAMP NOT NULL DEFAULT now()
);

-- ============================================================================
-- 判读规程迁移域（新增）
--   规则目录：新旧规程、类别定义、必要观察字段、生效日期、批准来源
--   迁移运行：读取归档观察与视频索引，生成影子分类、证据缺口与顺位影响
--   所有“运行”结果只增不改：规程再次修订只产生新的运行行
-- ============================================================================

-- ---------------------------------------------------------------- 判读规程版本
CREATE TABLE IF NOT EXISTS app_protocol (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    protocol_code      VARCHAR(48)  NOT NULL UNIQUE,
    name               VARCHAR(128) NOT NULL,
    effective_from     DATE         NOT NULL,
    effective_to       DATE,
    approval_source    VARCHAR(255) NOT NULL,
    status             VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    parent_protocol_id BIGINT REFERENCES app_protocol(id),
    note               TEXT,
    created_at         TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT chk_proto_status CHECK (status IN ('DRAFT','ACTIVE','SUPERSEDED')),
    CONSTRAINT chk_proto_range  CHECK (effective_to IS NULL OR effective_to >= effective_from)
);

-- 类别定义：新规程的判定类别与“必要观察字段”
CREATE TABLE IF NOT EXISTS app_protocol_category (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    protocol_id     BIGINT NOT NULL REFERENCES app_protocol(id),
    category_code   VARCHAR(48)  NOT NULL,
    category_name   VARCHAR(128) NOT NULL,
    defect_type     VARCHAR(32)  NOT NULL,
    min_grade       INTEGER      NOT NULL,
    max_grade       INTEGER      NOT NULL,
    required_fields VARCHAR(255) NOT NULL DEFAULT '',
    severity_grade  INTEGER      NOT NULL,
    enabled         BOOLEAN      NOT NULL DEFAULT true,
    note            TEXT,
    UNIQUE (protocol_id, category_code),
    CONSTRAINT chk_pc_type CHECK (defect_type IN ('CRACK','DEFORMATION','LEAK','JOINT_DISLOCATION')),
    CONSTRAINT chk_pc_grade CHECK (min_grade BETWEEN 1 AND 4 AND max_grade BETWEEN min_grade AND 4),
    CONSTRAINT chk_pc_sev CHECK (severity_grade BETWEEN 1 AND 4)
);

-- 新旧类别拆分 / 映射：一条旧类别可按字段条件拆为多个新类别
CREATE TABLE IF NOT EXISTS app_protocol_split (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_protocol_id   BIGINT NOT NULL REFERENCES app_protocol(id),
    from_category_code VARCHAR(48) NOT NULL,
    to_protocol_id     BIGINT NOT NULL REFERENCES app_protocol(id),
    to_category_code   VARCHAR(48) NOT NULL,
    condition_expr     VARCHAR(255) NOT NULL,
    priority           INTEGER     NOT NULL DEFAULT 10,
    note               TEXT,
    UNIQUE (from_protocol_id, from_category_code, to_protocol_id, to_category_code)
);

-- 依赖索引：哪些原始字段参与了哪些新类别的判定（增量重算的依据）
CREATE TABLE IF NOT EXISTS app_protocol_dependency (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    protocol_id        BIGINT NOT NULL REFERENCES app_protocol(id),
    category_code      VARCHAR(48) NOT NULL,
    field_name         VARCHAR(48) NOT NULL,
    source_field       VARCHAR(48) NOT NULL,
    source_defect_type VARCHAR(32) NOT NULL,
    dependency_kind    VARCHAR(16) NOT NULL DEFAULT 'SELF',
    condition_expr     VARCHAR(255),
    note               TEXT,
    UNIQUE (protocol_id, category_code, field_name),
    CONSTRAINT chk_pd_kind CHECK (dependency_kind IN ('SELF','CROSS_CATEGORY'))
);

-- 必要观察字段字典：
--   recoverability = NOT_MEASURABLE_FROM_ARCHIVE：旧视频画面无法回溯测量（如裂缝宽度），缺失时必须判证据不足，禁止由旧等级反推
--   recoverability = NOT_RECORDED：旧归档未登记但可重新观察（如渗漏迹象），缺失时保留多个候选，不任选其一
--   recoverability = ALWAYS_AVAILABLE：由归属/资产/批次直接可得
CREATE TABLE IF NOT EXISTS app_protocol_field (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    field_code     VARCHAR(48) NOT NULL UNIQUE,
    field_name     VARCHAR(128) NOT NULL,
    value_type     VARCHAR(16) NOT NULL,
    unit           VARCHAR(24),
    recoverability VARCHAR(32) NOT NULL,
    description    TEXT,
    CONSTRAINT chk_pf_type CHECK (value_type IN ('NUMERIC','CODE','TEXT')),
    CONSTRAINT chk_pf_reco CHECK (recoverability IN
        ('NOT_MEASURABLE_FROM_ARCHIVE','NOT_RECORDED','ALWAYS_AVAILABLE'))
);

-- 归档原始观察的可量化字段（宽度、渗漏、错位量等）
CREATE TABLE IF NOT EXISTS app_observation_field (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    observation_id BIGINT NOT NULL REFERENCES app_observation(id),
    field_name     VARCHAR(48) NOT NULL,
    field_value    VARCHAR(64) NOT NULL,
    source         VARCHAR(32) NOT NULL DEFAULT 'ARCHIVE_FRAME',
    UNIQUE (observation_id, field_name),
    CONSTRAINT chk_of_source CHECK (source IN ('ARCHIVE_FRAME','CONTRACTOR_SHEET','DERIVED'))
);

-- ---------------------------------------------------------------- 迁移运行（只增不改）
CREATE TABLE IF NOT EXISTS app_protocol_run (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_code            VARCHAR(96) NOT NULL UNIQUE,
    target_protocol_id  BIGINT NOT NULL REFERENCES app_protocol(id),
    base_protocol_id    BIGINT REFERENCES app_protocol(id),
    source_protocol_id  BIGINT REFERENCES app_protocol(id),
    as_of_version_id    BIGINT REFERENCES app_asset_version(id),
    mode                VARCHAR(16) NOT NULL,
    status              VARCHAR(16) NOT NULL DEFAULT 'RUNNING',
    started_at          TIMESTAMP NOT NULL DEFAULT now(),
    finished_at         TIMESTAMP,
    created_by          BIGINT REFERENCES app_user(id),
    observation_count   INTEGER NOT NULL DEFAULT 0,
    shadow_count        INTEGER NOT NULL DEFAULT 0,
    gap_count           INTEGER NOT NULL DEFAULT 0,
    ambiguous_count     INTEGER NOT NULL DEFAULT 0,
    reused_count        INTEGER NOT NULL DEFAULT 0,
    affected_categories TEXT,
    previous_run_id     BIGINT REFERENCES app_protocol_run(id),
    summary             TEXT,
    dependency_snapshot TEXT,
    dependency_warnings TEXT,
    CONSTRAINT chk_pr_mode   CHECK (mode IN ('FULL_REPLAY','INCREMENTAL')),
    CONSTRAINT chk_pr_status CHECK (status IN ('RUNNING','COMPLETED','FAILED'))
);

-- 影子分类：新规程下的候选类别；不覆盖原等级
CREATE TABLE IF NOT EXISTS app_shadow_classification (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id                BIGINT NOT NULL REFERENCES app_protocol_run(id),
    observation_id        BIGINT NOT NULL REFERENCES app_observation(id),
    segment_id            BIGINT REFERENCES app_pipe_segment(id),
    batch_id              BIGINT REFERENCES app_contractor_batch(id),
    defect_type           VARCHAR(32) NOT NULL,
    source_category_code  VARCHAR(48),
    target_category_code  VARCHAR(48),
    classification        VARCHAR(24) NOT NULL,
    old_grade             INTEGER,
    new_grade             INTEGER,
    evidence_strength     VARCHAR(8),
    missing_fields        VARCHAR(255),
    candidate_categories  VARCHAR(255),
    basis                 TEXT NOT NULL,
    applicability         VARCHAR(24) NOT NULL,
    applicability_note    TEXT,
    projected_segment_id  BIGINT REFERENCES app_pipe_segment(id),
    projected_start_m     NUMERIC(10,3),
    projected_end_m       NUMERIC(10,3),
    projection_note       TEXT,
    inspected_at          TIMESTAMP,
    evidence_uri          VARCHAR(255),
    video_uri             VARCHAR(255),
    stale_risk            BOOLEAN NOT NULL DEFAULT false,
    UNIQUE (run_id, observation_id),
    CONSTRAINT chk_sc_class CHECK (classification IN
        ('NEW_CATEGORY','AMBIGUOUS','EVIDENCE_GAP','OUT_OF_SCOPE','UNCLASSIFIED','SKIPPED_DUPLICATE')),
    CONSTRAINT chk_sc_appl CHECK (applicability IN
        ('APPLIES','NOT_APPLICABLE_BEFORE','NOT_APPLICABLE_AFTER'))
);
CREATE INDEX IF NOT EXISTS idx_sc_run_filter ON app_shadow_classification(run_id, defect_type, batch_id);
CREATE INDEX IF NOT EXISTS idx_sc_run_class ON app_shadow_classification(run_id, classification);

-- 旧类别在旧规程下的定义快照（规则差异查询用，历史运行不随规程修订漂移）
CREATE TABLE IF NOT EXISTS app_protocol_legacy_category (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    protocol_id   BIGINT NOT NULL REFERENCES app_protocol(id),
    category_code VARCHAR(48) NOT NULL,
    category_name VARCHAR(128) NOT NULL,
    defect_type   VARCHAR(32) NOT NULL,
    min_grade     INTEGER NOT NULL,
    max_grade     INTEGER NOT NULL,
    note          TEXT,
    UNIQUE (protocol_id, category_code),
    CONSTRAINT chk_plc_type CHECK (defect_type IN ('CRACK','DEFORMATION','LEAK','JOINT_DISLOCATION'))
);

-- 新旧顺位变化：旧发布口径与影子口径分开保存
CREATE TABLE IF NOT EXISTS app_shadow_segment_rank (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id                BIGINT NOT NULL REFERENCES app_protocol_run(id),
    segment_id            BIGINT NOT NULL REFERENCES app_pipe_segment(id),
    old_published_rank    INTEGER,
    old_published_max_grade INTEGER,
    old_published_burden  NUMERIC(12,3),
    shadow_rank           INTEGER,
    shadow_max_grade      INTEGER,
    shadow_burden         NUMERIC(12,3),
    rank_delta            INTEGER,
    gap_count             INTEGER NOT NULL DEFAULT 0,
    ambiguous_count       INTEGER NOT NULL DEFAULT 0,
    affected              BOOLEAN NOT NULL DEFAULT false,
    note                  TEXT,
    UNIQUE (run_id, segment_id)
);

-- 人工复核：按缺陷类型与来源批次复核候选，单独保存，不改写影子结果
CREATE TABLE IF NOT EXISTS app_shadow_review (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id          BIGINT NOT NULL REFERENCES app_protocol_run(id),
    shadow_id       BIGINT NOT NULL REFERENCES app_shadow_classification(id),
    reviewer_id     BIGINT REFERENCES app_user(id),
    decision        VARCHAR(32) NOT NULL,
    chosen_category VARCHAR(48),
    note            TEXT NOT NULL,
    created_at      TIMESTAMP NOT NULL DEFAULT now(),
    CONSTRAINT chk_sr_decision CHECK (decision IN
        ('ACCEPT_SHADOW','KEEP_OLD','NEEDS_VIDEO','CONFIRM_CANDIDATE'))
);
CREATE INDEX IF NOT EXISTS idx_sr_run ON app_shadow_review(run_id, shadow_id);
